import sys

base = bytearray(open(sys.argv[1], 'rb').read())
assert len(base) == 2048

def latin(c):
    return [''.join('#' if (base[ord(c) * 8 + y] >> x) & 1 else '.' for x in range(8)) for y in range(8)]

E = '........'
def g(*rows, top=0):
    """filas desde la fila top; el resto en blanco"""
    out = [E] * 8
    for i, r in enumerate(rows):
        assert len(r) == 8, r
        out[top + i] = r
    return out

