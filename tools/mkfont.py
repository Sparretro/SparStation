# Las letras con tilde de la página 437 están pegadas a la izquierda y las ASCII a la derecha: una columna más allá
# (si cabe) para que «más» no se vea apelotonado
for c in [0x81, 0x82, 0x90, 0x9a, 0xa0, 0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xad, 0xae, 0xaf]:
    rows = base[c * 8:c * 8 + 8]
    if not any(r & 0x80 for r in rows):
        for y in range(8):
            base[c * 8 + y] = (rows[y] << 1) & 0xff
order = [chr(0x410 + i) for i in range(64)] + ['Ё', 'ё']
glyphs = {**U, **L}
for i, ch in enumerate(order):
    rows = glyphs[ch]
    for y in range(8):
        base[(0xB0 + i) * 8 + y] = sum(1 << x for x in range(8) if rows[y][x] == '#')

with open(sys.argv[2], 'w', encoding='utf-8') as f:
    f.write('// Generado por tools/mkfont.py: fuente de la consola (página 437 de libnds + cirílico en B0h..F1h)\n')
    f.write('#include <nds/ndstypes.h>\nconst u8 spar_font[2048] __attribute__((aligned(4))) = {\n')
    for i in range(0, 2048, 16):
        f.write('\t' + ', '.join('0x%02x' % b for b in base[i:i + 16]) + ',\n')
    f.write('};\n')
